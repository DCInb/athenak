#!/usr/bin/env python3
"""Build and run coupled/control laser-target cases with AthenaK's local helper."""

from __future__ import annotations

import argparse
import csv
import os
from pathlib import Path
import shutil
import subprocess
import time


BENCH_DIR = Path(__file__).resolve().parent
REPO = BENCH_DIR.parent
BASE_INPUT = BENCH_DIR / "laser_target.athinput"
BUILD_DIR = BENCH_DIR / "build"
BINARY = BUILD_DIR / "src" / "athena"
HELPER = Path(
    "/home/mengqi/.codex/skills/athenak-build-run/scripts/athenak_case.sh"
)
PROBLEM = "../../laser-target/laser_target"

CASES = (
    {
        "name": "coupled_gpu1",
        "ranks": 1,
        "replacements": {},
        "description": "laser + electron/radiation coupling + Biermann",
    },
    {
        "name": "coupled_gpu2",
        "ranks": 2,
        "replacements": {},
        "description": "MPI-decomposed copy of the coupled case",
    },
    {
        "name": "no_radiation_gpu1",
        "ranks": 1,
        "replacements": {"couple_matter = true": "couple_matter = false"},
        "description": "control with electron/radiation source exchange disabled",
    },
    {
        "name": "no_biermann_gpu1",
        "ranks": 1,
        "replacements": {
            "biermann_coefficient = 2.0e-2": "biermann_coefficient = 0.0"
        },
        "description": "control with the Biermann source coefficient set to zero",
    },
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--build", action="store_true", help="configure and build before running"
    )
    parser.add_argument(
        "--clean",
        action="store_true",
        help="remove this benchmark's prior runs, logs, and summaries first",
    )
    parser.add_argument("--jobs", type=int, default=40, help="parallel build jobs")
    parser.add_argument(
        "--gpus",
        default=os.environ.get("ATHENAK_TEST_GPUS", "2,3,4,5"),
        help="comma-separated CUDA device IDs (default: ATHENAK_TEST_GPUS or 2,3,4,5)",
    )
    return parser.parse_args()


def clean_outputs() -> None:
    for path in (
        BENCH_DIR / "runs",
        BENCH_DIR / "logs",
        BENCH_DIR / "plots",
        BENCH_DIR / "run_status.csv",
        BENCH_DIR / "results.csv",
        BENCH_DIR / "results.json",
        BENCH_DIR / "diagnostics.md",
    ):
        if path.is_dir():
            shutil.rmtree(path)
        elif path.exists():
            path.unlink()


def build(jobs: int) -> None:
    command = [
        str(HELPER),
        "build",
        "--problem",
        PROBLEM,
        "--repo",
        str(REPO),
        "--build-dir",
        str(BUILD_DIR),
        "--jobs",
        str(jobs),
    ]
    subprocess.run(command, cwd=REPO, check=True)


def case_input(case: dict[str, object], run_dir: Path) -> Path:
    text = BASE_INPUT.read_text()
    basename = f"laser_target_{case['name']}"
    replacements = {
        "basename = laser_target": f"basename = {basename}",
        **case["replacements"],
    }
    for old, new in replacements.items():
        count = text.count(old)
        if count != 1:
            raise RuntimeError(f"Expected one occurrence of {old!r}, found {count}")
        text = text.replace(old, new)
    output = run_dir / f"{case['name']}.athinput"
    output.write_text(
        f"# Generated by run_benchmark.py: {case['description']}\n" + text
    )
    return output


def prepare_run_dir(case_name: str) -> Path:
    run_dir = BENCH_DIR / "runs" / case_name
    if run_dir.exists():
        generated = list(run_dir.iterdir())
        if generated:
            raise RuntimeError(
                f"Refusing to overwrite {run_dir}; rerun with --clean if intended"
            )
    source_dir = run_dir / "src"
    source_dir.mkdir(parents=True, exist_ok=True)
    (source_dir / "athena").symlink_to(BINARY)
    return run_dir


def main() -> int:
    args = parse_args()
    devices = [item.strip() for item in args.gpus.split(",") if item.strip()]
    if len(devices) < 2:
        raise RuntimeError("At least two GPU IDs are required for the MPI comparison")
    if args.clean:
        clean_outputs()
    if args.build:
        build(args.jobs)
    if not BINARY.is_file():
        raise RuntimeError(f"Missing AthenaK binary {BINARY}; use --build")

    (BENCH_DIR / "logs").mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, object]] = []
    for case in CASES:
        name = str(case["name"])
        ranks = int(case["ranks"])
        run_dir = prepare_run_dir(name)
        input_path = case_input(case, run_dir)
        log_path = BENCH_DIR / "logs" / f"{name}.log"
        command = [
            str(HELPER),
            "run",
            "--problem",
            PROBLEM,
            "--repo",
            str(REPO),
            "--build-dir",
            str(run_dir),
            "--input",
            str(input_path),
            "--ranks",
            str(ranks),
        ]
        env = os.environ.copy()
        env["CUDA_VISIBLE_DEVICES"] = ",".join(devices[:ranks])
        print(
            f"START case={name} ranks={ranks} "
            f"visible={env['CUDA_VISIBLE_DEVICES']}",
            flush=True,
        )
        start = time.monotonic()
        with log_path.open("w") as log:
            log.write("command=" + " ".join(command) + "\n")
            log.write(f"CUDA_VISIBLE_DEVICES={env['CUDA_VISIBLE_DEVICES']}\n")
            log.flush()
            result = subprocess.run(
                command,
                cwd=REPO,
                env=env,
                text=True,
                stdout=log,
                stderr=subprocess.STDOUT,
                check=False,
            )
        elapsed = time.monotonic() - start
        rows.append(
            {
                "case": name,
                "description": case["description"],
                "gpus": ranks,
                "visible_devices": env["CUDA_VISIBLE_DEVICES"],
                "input": input_path,
                "run_dir": run_dir,
                "log": log_path,
                "exit_code": result.returncode,
                "elapsed_seconds": f"{elapsed:.6f}",
            }
        )
        print(
            f"DONE case={name} exit={result.returncode} elapsed={elapsed:.3f}s",
            flush=True,
        )

    with (BENCH_DIR / "run_status.csv").open("w", newline="") as output:
        writer = csv.DictWriter(output, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return 1 if any(int(row["exit_code"]) != 0 for row in rows) else 0


if __name__ == "__main__":
    raise SystemExit(main())
